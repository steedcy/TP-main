// TC-017.S1/S3: live device type list, capability matrix, and export control.
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core')
const root = path.resolve(__dirname, '../..')
const line = fs.readFileSync(path.join(root, 'user.md'), 'utf8').split(/\r?\n/)
  .find(value => value.startsWith('|配置管理员|'))
const [, , username, password] = line.split('|')

async function main() {
  const browser = await chromium.launch({ executablePath: 'C:\\Users\\savy\\AppData\\Local\\Google\\Chrome\\Application\\chrome.exe', headless: true })
  const ev = { observedAt: new Date().toISOString(), runtimeInput: 'V1.5', browser: 'Chrome', viewport: '1366x768' }
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
    await page.goto('http://127.0.0.1:5173/login', { waitUntil: 'networkidle' })
    await page.locator('input[placeholder="账号"]').fill(username)
    await page.locator('input[placeholder="密码"]').fill(password)
    await page.locator('button[type="submit"]').click()
    await page.waitForURL('**/overview')
    await page.goto('http://127.0.0.1:5173/device-types', { waitUntil: 'networkidle' })
    ev.listRowCount = await page.locator('.ant-table-row').count()
    ev.listHeaders = await page.locator('.ant-table:visible').first().locator('.ant-table-thead th').allInnerTexts()
    ev.listHasCountColumns = ev.listHeaders.some(x => /支持能力数|模板数|实例数/.test(x))
    ev.addDeleteTypeButtons = await page.getByRole('button', { name: /新增设备类型|删除设备类型/ }).count()
    await page.screenshot({ path: path.join(__dirname, 'evidence', 'TC-017-type-list.png') })
    await page.getByRole('button', { name: '查看详情' }).first().click()
    const drawer = page.locator('.ant-drawer-content')
    await drawer.getByText('设备类型详情').waitFor({ state: 'visible' })
    const detailText = await drawer.innerText()
    ev.detailShowsInstanceCount = /已创建实例数/.test(detailText)
    ev.detailShowsSupportedCapabilityCount = /支持能力数/.test(detailText)
    ev.detailShowsTemplateCount = /模板数/.test(detailText)
    ev.detailCheckedCapabilities = await drawer.locator('.ant-checkbox-checked').count()
    ev.detailTemplateRows = await drawer.locator('.ant-table-row').count()
    await page.screenshot({ path: path.join(__dirname, 'evidence', 'TC-017-type-detail.png') })
    await drawer.locator('.ant-drawer-close').click()
    await page.getByText('能力约束矩阵', { exact: true }).click()
    ev.matrixRowCount = await page.locator('.ant-table:visible').last().locator('.ant-table-row').count()
    ev.matrixHeaders = await page.locator('.ant-table:visible').last().locator('.ant-table-thead th').allInnerTexts()
    ev.exportControlCount = await page.getByRole('button', { name: /导出|Excel/ }).count()
    await page.screenshot({ path: path.join(__dirname, 'evidence', 'TC-017-type-matrix.png') })
  } finally { await browser.close() }
  fs.writeFileSync(path.join(__dirname, 'evidence', 'TC-017-type-boundary.json'), JSON.stringify(ev, null, 2) + '\n')
  process.stdout.write(JSON.stringify(ev) + '\n')
}
main().catch(error => { process.stderr.write(String(error) + '\n'); process.exitCode = 1 })
